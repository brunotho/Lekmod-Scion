"""Copies website/data/essentials.txt into the Civilopedia home page texts (user, 2026-10-22).

Rerun after every change to the Essentials page; the generated block in CIV5Units_Mongol.xml (between the
LEKMOD ESSENTIALS markers) is replaced each time. Keys:
  TXT_KEY_LEKMOD_PEDIA_ESSENTIALS_INTRO      the paragraph before the first heading
  TXT_KEY_LEKMOD_PEDIA_ESSENTIALS_<n>_HEADER / _<n>_TEXT   one per "## " section, n from 1
CivilopediaScreen.lua (home page) shows sections 1, 2, ... until a key is missing.
"""
import os
import re
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'website', 'data', 'essentials.txt')
DST = os.path.join(ROOT, 'LEKMOD', 'Override', 'CIV5Units_Mongol.xml')
BEGIN = '\t\t<!-- LEKMOD ESSENTIALS BEGIN (generated by tools/sync_pedia_essentials.py from website/data/essentials.txt) -->\n'
END = '\t\t<!-- LEKMOD ESSENTIALS END -->\n'


def rows():
    intro, sections = [], []
    for line in open(SRC, encoding='utf-8').read().replace('\r\n', '\n').split('\n'):
        line = line.rstrip()
        if not line.strip():
            continue
        if line.startswith('## '):
            sections.append([line[3:].strip(), []])
        elif sections:
            sections[-1][1].append(line)
        else:
            intro.append(line)
    out = [('TXT_KEY_LEKMOD_PEDIA_ESSENTIALS_INTRO', ' '.join(intro))]
    for n, (head, lines) in enumerate(sections, 1):
        items = [re.sub(r'^\s*-\s+', '[ICON_BULLET]', l) for l in lines]
        out.append(('TXT_KEY_LEKMOD_PEDIA_ESSENTIALS_%d_HEADER' % n, head))
        out.append(('TXT_KEY_LEKMOD_PEDIA_ESSENTIALS_%d_TEXT' % n, '[NEWLINE]'.join(items)))
    return out


def main():
    b = open(DST, 'rb').read()
    crlf = b'\r\n' in b
    s = b.decode('utf-8', errors='surrogateescape').replace('\r\n', '\n')
    block = BEGIN + ''.join('\t\t<Row Tag="%s">\n\t\t\t<Text>%s</Text>\n\t\t</Row>\n' % (k, escape(v)) for k, v in rows()) + END
    if BEGIN in s:
        a = s.index(BEGIN)
        z = s.index(END) + len(END)
        s = s[:a] + block + s[z:]
    else:
        anchor = '\t</Language_en_US>'
        assert s.count(anchor) == 1
        s = s.replace(anchor, block + anchor)
    if crlf:
        s = s.replace('\n', '\r\n')
    open(DST, 'wb').write(s.encode('utf-8', errors='surrogateescape'))
    print('essentials synced:', len(rows()), 'texts')


if __name__ == '__main__':
    main()
