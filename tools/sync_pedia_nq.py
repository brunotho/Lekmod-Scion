"""Copies the No Quitters rule set (a Google Doc) into the Civilopedia NQ tab texts (user, 2026-10-22).

usage: python tools/sync_pedia_nq.py [--offline]
Downloads the doc as plain text (DOC_URL export), saves it as docs/nq_rules.txt (so changes show in git diff),
then replaces the generated block in CIV5Units_Mongol.xml (between the LEKMOD NQ RULES markers).
--offline skips the download and uses docs/nq_rules.txt as it is.
Doc layout read: the first line is the title, the second the subtitle; short lines without a final "." are section
headings; "* " lines are bullets ("   * " one level deeper); other lines are paragraphs of the current section.
Keys:
  TXT_KEY_LEKMOD_PEDIA_NQ_TITLE / _INTRO      the doc's title and subtitle
  TXT_KEY_LEKMOD_PEDIA_NQ_<n>_HEADER / _<n>_TEXT   one per section, n from 1
CivilopediaScreen.lua (NQ tab) shows sections 1, 2, ... until a key is missing.
"""
import os
import re
import sys
import urllib.request
from xml.sax.saxutils import escape

DOC_URL = 'https://docs.google.com/document/d/1re6vdlTrHlaFxzIt4QlJsqsd60_4d-4ivUPhQxHYebg/export?format=txt'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'docs', 'nq_rules.txt')
DST = os.path.join(ROOT, 'LEKMOD', 'Override', 'CIV5Units_Mongol.xml')
BEGIN = '\t\t<!-- LEKMOD NQ RULES BEGIN (generated by tools/sync_pedia_nq.py from the No Quitters rules doc) -->\n'
END = '\t\t<!-- LEKMOD NQ RULES END -->\n'
SUB_INDENT = '      '


def download():
    text = urllib.request.urlopen(DOC_URL, timeout=30).read().decode('utf-8-sig')
    text = text.replace('\r\n', '\n').rstrip() + '\n'
    open(SRC, 'w', encoding='utf-8', newline='\n').write(text)


def rows():
    lines = [l.rstrip() for l in open(SRC, encoding='utf-8-sig').read().split('\n') if l.strip()]
    title, intro = lines[0].strip(), lines[1].strip()
    sections = []
    for line in lines[2:]:
        m = re.match(r'^(\s*)\*\s+(.*)$', line)
        if m:
            item = ('[ICON_BULLET]' if not m.group(1) else SUB_INDENT + '- ') + m.group(2).strip()
            sections[-1][1].append(item)
        elif len(line.strip()) < 60 and not line.strip().endswith(('.', ':', '!')):
            sections.append([line.strip(), []])
        else:
            sections[-1][1].append('[NEWLINE]' + line.strip() if sections[-1][1] else line.strip())
    out = [('TXT_KEY_LEKMOD_PEDIA_NQ_TITLE', title), ('TXT_KEY_LEKMOD_PEDIA_NQ_INTRO', intro)]
    for n, (head, items) in enumerate(sections, 1):
        out.append(('TXT_KEY_LEKMOD_PEDIA_NQ_%d_HEADER' % n, head))
        out.append(('TXT_KEY_LEKMOD_PEDIA_NQ_%d_TEXT' % n, '[NEWLINE]'.join(items)))
    return out


def main():
    if '--offline' not in sys.argv:
        download()
    b = open(DST, 'rb').read()
    crlf = b'\r\n' in b
    s = b.decode('utf-8', errors='surrogateescape').replace('\r\n', '\n')
    texts = rows()
    block = BEGIN + ''.join('\t\t<Row Tag="%s">\n\t\t\t<Text>%s</Text>\n\t\t</Row>\n' % (k, escape(v)) for k, v in texts) + END
    if BEGIN in s:
        a = s.index(BEGIN)
        z = s.index(END) + len(END)
        s = s[:a] + block + s[z:]
    else:
        anchor = '\t</Language_en_US>'
        assert s.count(anchor) == 1
        s = s.replace(anchor, block + anchor)
    if crlf:
        s = s.replace('\n', '\r\n')
    open(DST, 'wb').write(s.encode('utf-8', errors='surrogateescape'))
    print('nq rules synced:', (len(texts) - 2) // 2, 'sections')


if __name__ == '__main__':
    main()
